-- =====================================================================
-- Central+ · notificações com o app fechado (push)
-- =====================================================================
-- Rode no SQL Editor do projeto do CENTRAL+. Pode rodar de novo.
--
-- Como funciona:
--   1. Cada aparelho que ativa as notificações fica em push_inscricoes.
--   2. Quando algo acontece (solicitação nova, status, encaminhamento,
--      resposta), um gatilho do banco chama a Edge Function "notificar",
--      que decide quem recebe e envia o aviso.
--
-- DEPOIS de rodar, configure o endereço e o segredo (seção 4, no final).
-- =====================================================================

begin;

-- pg_net: permite ao banco chamar a Edge Function (é do próprio Supabase)
create extension if not exists pg_net;

-- ---------------------------------------------------------------------
-- 1. Configuração privada (não aparece na API)
-- ---------------------------------------------------------------------

create schema if not exists privado;
revoke all on schema privado from public, anon, authenticated;

create table if not exists privado.config (
  chave text primary key,
  valor text not null
);

-- ---------------------------------------------------------------------
-- 2. Aparelhos inscritos
-- ---------------------------------------------------------------------

create table if not exists public.push_inscricoes (
  id             bigint generated by default as identity primary key,
  usuario_id     uuid not null references auth.users(id) on delete cascade,
  plataforma     text not null check (plataforma in ('web', 'android')),
  endpoint       text not null unique, -- web: endereço da inscrição; android: token do Firebase
  p256dh         text,                 -- só web
  auth           text,                 -- só web
  aparelho       text,
  criado_em      timestamptz not null default now(),
  atualizado_em  timestamptz not null default now()
);

create index if not exists push_inscricoes_usuario_idx on public.push_inscricoes (usuario_id);

alter table public.push_inscricoes enable row level security;

drop policy if exists push_select_proprio on public.push_inscricoes;
create policy push_select_proprio on public.push_inscricoes
  for select to authenticated using (usuario_id = auth.uid());

grant select on public.push_inscricoes to authenticated;
revoke insert, update, delete on public.push_inscricoes from authenticated, anon;
revoke all on public.push_inscricoes from anon;

-- Inscreve (ou atualiza) este aparelho para o usuário logado.
-- Se o aparelho era de outra pessoa, passa a ser de quem está logado agora.
create or replace function public.registrar_push(
  p_plataforma text, p_endpoint text, p_p256dh text default null, p_auth text default null, p_aparelho text default null
) returns void language plpgsql security definer set search_path = public as $$
begin
  if not public.eh_usuario_ativo() then
    raise exception 'Sem acesso.' using errcode = '42501';
  end if;
  if p_plataforma not in ('web', 'android') or coalesce(p_endpoint, '') = '' then
    raise exception 'Inscrição inválida.' using errcode = '22023';
  end if;
  if p_plataforma = 'web' and (coalesce(p_p256dh, '') = '' or coalesce(p_auth, '') = '') then
    raise exception 'Inscrição web sem chaves.' using errcode = '22023';
  end if;

  insert into push_inscricoes (usuario_id, plataforma, endpoint, p256dh, auth, aparelho)
  values (auth.uid(), p_plataforma, p_endpoint, p_p256dh, p_auth, left(p_aparelho, 200))
  on conflict (endpoint) do update
    set usuario_id = excluded.usuario_id,
        plataforma = excluded.plataforma,
        p256dh = excluded.p256dh,
        auth = excluded.auth,
        aparelho = excluded.aparelho,
        atualizado_em = now();
end $$;

-- Tira este aparelho (usado no botão "Sair")
create or replace function public.remover_push(p_endpoint text)
returns void language sql security definer set search_path = public as $$
  delete from push_inscricoes where endpoint = p_endpoint and usuario_id = auth.uid();
$$;

revoke execute on function public.registrar_push(text, text, text, text, text) from public, anon;
grant execute on function public.registrar_push(text, text, text, text, text) to authenticated;
revoke execute on function public.remover_push(text) from public, anon;
grant execute on function public.remover_push(text) to authenticated;

-- ---------------------------------------------------------------------
-- 3. Gatilhos que avisam a Edge Function
-- ---------------------------------------------------------------------

-- Envia o evento para a função "notificar". Nunca faz a gravação falhar:
-- se a configuração faltar ou a chamada der erro, só registra um aviso.
create or replace function privado.disparar_notificacao(p_evento jsonb)
returns void language plpgsql security definer set search_path = public, privado as $$
declare
  v_url     text;
  v_segredo text;
begin
  select valor into v_url from privado.config where chave = 'notificar_url';
  select valor into v_segredo from privado.config where chave = 'notificar_segredo';
  if v_url is null or v_segredo is null then
    return;
  end if;

  perform net.http_post(
    url := v_url,
    body := p_evento,
    headers := jsonb_build_object('Content-Type', 'application/json', 'x-central-segredo', v_segredo),
    timeout_milliseconds := 8000
  );
exception when others then
  raise warning 'Central+: não foi possível disparar a notificação: %', sqlerrm;
end $$;

revoke all on function privado.disparar_notificacao(jsonb) from public, anon, authenticated;

create or replace function privado.solicitacoes_notificar()
returns trigger language plpgsql security definer set search_path = public, privado as $$
begin
  if tg_op = 'INSERT' then
    perform privado.disparar_notificacao(jsonb_build_object(
      'tipo', 'nova', 'id', new.id, 'autor', new.criador_id));
  elsif tg_op = 'UPDATE' then
    if new.setor is distinct from old.setor then
      perform privado.disparar_notificacao(jsonb_build_object(
        'tipo', 'encaminhada', 'id', new.id, 'de', old.setor, 'autor', new.atualizado_por));
    end if;
    if new.status is distinct from old.status then
      perform privado.disparar_notificacao(jsonb_build_object(
        'tipo', 'status', 'id', new.id, 'autor', new.atualizado_por));
    end if;
  end if;
  return null;
end $$;

drop trigger if exists trg_solicitacoes_notificar on public.solicitacoes;
create trigger trg_solicitacoes_notificar
  after insert or update of status, setor on public.solicitacoes
  for each row execute function privado.solicitacoes_notificar();

create or replace function privado.respostas_notificar()
returns trigger language plpgsql security definer set search_path = public, privado as $$
begin
  if new.tipo = 'resposta' then
    perform privado.disparar_notificacao(jsonb_build_object(
      'tipo', 'resposta', 'id', new.solicitacao_id, 'autor', new.autor_id,
      'autor_nome', new.autor_nome, 'texto', left(new.texto, 300)));
  end if;
  return null;
end $$;

drop trigger if exists trg_respostas_notificar on public.respostas_solicitacao;
create trigger trg_respostas_notificar
  after insert on public.respostas_solicitacao
  for each row execute function privado.respostas_notificar();

commit;

