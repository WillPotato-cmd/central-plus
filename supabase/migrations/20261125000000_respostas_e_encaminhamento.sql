-- =====================================================================
-- Central+ · histórico de respostas e troca de setor
-- =====================================================================
-- Rode DEPOIS de 20261124000000_central_plus.sql. Pode rodar de novo
-- sem problema. Ele:
--   1. cria a tabela respostas_solicitacao (todas as respostas ficam
--      guardadas, com nome e cargo de quem respondeu);
--   2. copia para ela as respostas que já existem hoje;
--   3. troca a função responder_solicitacao para gravar no histórico;
--   4. cria a função encaminhar_solicitacao (trocar o setor responsável),
--      liberada para quem atende o setor atual e para a Supervisão de operação.
-- =====================================================================

begin;

-- ---------------------------------------------------------------------
-- 1. Tabela de respostas
-- ---------------------------------------------------------------------

create table if not exists public.respostas_solicitacao (
  id              bigint generated by default as identity primary key,
  solicitacao_id  text        not null,
  autor_id        uuid,
  autor_nome      text        not null,
  autor_tag       text,
  tipo            text        not null default 'resposta'
                  check (tipo in ('resposta', 'encaminhamento')),
  texto           text        not null,
  criado_em       timestamptz not null default now()
);

create index if not exists respostas_solicitacao_sol_idx
  on public.respostas_solicitacao (solicitacao_id, criado_em);

-- Ao excluir uma solicitação, apaga as respostas dela
create or replace function public.solicitacoes_apagar_respostas()
returns trigger language plpgsql security definer set search_path = public as $$
begin
  delete from respostas_solicitacao where solicitacao_id = old.id;
  return old;
end $$;

drop trigger if exists trg_solicitacoes_apagar_respostas on public.solicitacoes;
create trigger trg_solicitacoes_apagar_respostas
  after delete on public.solicitacoes
  for each row execute function public.solicitacoes_apagar_respostas();

-- ---------------------------------------------------------------------
-- 2. Respostas antigas (campo "resposta" da solicitação) vão para o histórico
-- ---------------------------------------------------------------------

insert into public.respostas_solicitacao (solicitacao_id, autor_id, autor_nome, autor_tag, texto, criado_em)
select s.id,
       u.id,
       coalesce(u.nome, 'Central'),
       u.tag,
       s.resposta,
       coalesce(s.atualizado_em, now())
from public.solicitacoes s
left join public.usuarios u on u.id = s.respondido_por
where coalesce(trim(s.resposta), '') <> ''
  and not exists (select 1 from public.respostas_solicitacao r where r.solicitacao_id = s.id);

-- ---------------------------------------------------------------------
-- 3. Segurança: vê as respostas quem pode ver a solicitação.
--    Ninguém grava direto; só pelas funções abaixo.
-- ---------------------------------------------------------------------

alter table public.respostas_solicitacao enable row level security;

drop policy if exists respostas_select on public.respostas_solicitacao;
create policy respostas_select on public.respostas_solicitacao
  for select to authenticated
  using (exists (
    select 1 from public.solicitacoes s
    where s.id = respostas_solicitacao.solicitacao_id
      and (public.pode_ver_loja(s.loja) or public.pode_gerenciar_setor(s.setor))
  ));

grant select on public.respostas_solicitacao to authenticated;
revoke insert, update, delete on public.respostas_solicitacao from authenticated, anon;
revoke all on public.respostas_solicitacao from anon;

-- ---------------------------------------------------------------------
-- 4. Funções
-- ---------------------------------------------------------------------

-- Quem pode trocar o setor: quem atende o setor ATUAL da solicitação
-- (Diretoria, Supervisão administrativa, Central do setor) e também a
-- Supervisão de operação.
create or replace function public.pode_encaminhar(p_setor text)
returns boolean language sql stable security definer set search_path = public as $$
  select public.pode_gerenciar_setor(p_setor) or exists (
    select 1 from usuarios
    where id = auth.uid() and coalesce(ativo, true)
      and tag = 'Supervisão' and tipo_supervisao = 'operacao'
  );
$$;

create or replace function public.responder_solicitacao(p_id text, p_texto text)
returns public.solicitacoes language plpgsql security definer set search_path = public as $$
declare
  v_sol  solicitacoes;
  v_user usuarios;
  v_txt  text := left(trim(coalesce(p_texto, '')), 2000);
begin
  if v_txt = '' then
    raise exception 'Resposta vazia.' using errcode = '22023';
  end if;

  select * into v_sol from solicitacoes where id = p_id for update;
  if v_sol.id is null then
    raise exception 'Solicitação não encontrada.' using errcode = 'P0002';
  end if;
  if not public.pode_gerenciar_setor(v_sol.setor) then
    raise exception 'Sem permissão para este setor.' using errcode = '42501';
  end if;

  select * into v_user from usuarios where id = auth.uid();

  insert into respostas_solicitacao (solicitacao_id, autor_id, autor_nome, autor_tag, tipo, texto)
  values (p_id, v_user.id, v_user.nome, v_user.tag, 'resposta', v_txt);

  -- O campo "resposta" continua guardando a última, por compatibilidade
  update solicitacoes
     set resposta = v_txt,
         respondido_por = auth.uid(),
         atualizado_em = now(),
         atualizado_por = auth.uid()
   where id = p_id
  returning * into v_sol;

  perform public.registrar_log('Respondeu a solicitação ' || p_id);
  return v_sol;
end $$;

create or replace function public.encaminhar_solicitacao(p_id text, p_setor text)
returns public.solicitacoes language plpgsql security definer set search_path = public as $$
declare
  v_sol      solicitacoes;
  v_user     usuarios;
  v_anterior text;
begin
  if p_setor not in ('Recursos Humanos', 'Departamento Pessoal', 'Administrativo', 'Compras',
                     'Manutenção', 'Logistica', 'Marketing', 'TI') then
    raise exception 'Setor inválido.' using errcode = '22023';
  end if;

  select * into v_sol from solicitacoes where id = p_id for update;
  if v_sol.id is null then
    raise exception 'Solicitação não encontrada.' using errcode = 'P0002';
  end if;
  if not public.pode_encaminhar(v_sol.setor) then
    raise exception 'Sem permissão para este setor.' using errcode = '42501';
  end if;
  if v_sol.setor = p_setor then
    return v_sol;
  end if;

  v_anterior := v_sol.setor;
  select * into v_user from usuarios where id = auth.uid();

  update solicitacoes
     set setor = p_setor, atualizado_em = now(), atualizado_por = auth.uid()
   where id = p_id
  returning * into v_sol;

  insert into respostas_solicitacao (solicitacao_id, autor_id, autor_nome, autor_tag, tipo, texto)
  values (p_id, v_user.id, v_user.nome, v_user.tag, 'encaminhamento',
          'Encaminhou de ' || v_anterior || ' para ' || p_setor);

  perform public.registrar_log('Encaminhou a solicitação ' || p_id || ' de ' || v_anterior || ' para ' || p_setor);
  return v_sol;
end $$;

revoke execute on function public.encaminhar_solicitacao(text, text) from public, anon;
grant execute on function public.encaminhar_solicitacao(text, text) to authenticated;
revoke execute on function public.responder_solicitacao(text, text) from public, anon;
grant execute on function public.responder_solicitacao(text, text) to authenticated;

-- ---------------------------------------------------------------------
-- 5. Tempo real para as respostas
-- ---------------------------------------------------------------------

do $$ begin
  alter publication supabase_realtime add table public.respostas_solicitacao;
exception when duplicate_object then null; when undefined_object then null; end $$;

commit;
