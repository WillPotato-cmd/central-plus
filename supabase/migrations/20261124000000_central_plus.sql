-- 6. Storage
-- ---------------------------------------------------------------------
-- anexos-solicitacoes: fotos das solicitações. Caminho: <uid>/<arquivo>
-- auditorias:          relatórios. Caminho: <ano>/<tipo>/<arquivo>
-- Ambos privados: as imagens são abertas por URL assinada de 1 hora.

insert into storage.buckets (id, name, public)
values ('anexos-solicitacoes', 'anexos-solicitacoes', false),
       ('auditorias', 'auditorias', false)
on conflict (id) do update set public = false;

do $$
declare p record;
begin
  for p in
    select policyname from pg_policies
    where schemaname = 'storage' and tablename = 'objects'
      and (policyname like 'anexos_%' or policyname like 'auditorias_%')
  loop
    execute format('drop policy %I on storage.objects', p.policyname);
  end loop;
end $$;

-- Enviar foto: só na própria pasta (<uid>/...)
create policy anexos_insert on storage.objects
  for insert to authenticated
  with check (
    bucket_id = 'anexos-solicitacoes'
    and public.eh_usuario_ativo()
    and (storage.foldername(name))[1] = auth.uid()::text
  );

-- Ver foto: dono do arquivo, ou quem pode ver a solicitação que a usa
create policy anexos_select on storage.objects
  for select to authenticated
  using (
    bucket_id = 'anexos-solicitacoes'
    and (
      (storage.foldername(name))[1] = auth.uid()::text
      or exists (
        select 1 from public.solicitacoes s
        where s.imagem = storage.objects.name
          and (public.pode_ver_loja(s.loja) or public.pode_gerenciar_setor(s.setor))
      )
    )
  );

-- Apagar foto: Diretoria, ou o dono (para limpar envio que falhou)
create policy anexos_delete on storage.objects
  for delete to authenticated
  using (
    bucket_id = 'anexos-solicitacoes'
    and (public.eh_diretoria() or (storage.foldername(name))[1] = auth.uid()::text)
  );

create policy auditorias_files_select on storage.objects
  for select to authenticated
  using (
    bucket_id = 'auditorias'
    and exists (
      select 1 from public.auditoria_documentos d
      where d.caminho = storage.objects.name
        and public.pode_ver_auditoria(d.loja)
    )
  );

create policy auditorias_files_write on storage.objects
  for insert to authenticated
  with check (bucket_id = 'auditorias' and public.eh_diretoria());

create policy auditorias_files_update on storage.objects
  for update to authenticated
  using (bucket_id = 'auditorias' and public.eh_diretoria());

create policy auditorias_files_delete on storage.objects
  for delete to authenticated
  using (bucket_id = 'auditorias' and public.eh_diretoria());

