-- =====================================================================
-- Central+ · migração de banco e segurança (RLS)
-- =====================================================================
-- Pode ser executada no SQL Editor do Supabase. É idempotente: rodar de
-- novo não duplica nada. Ela:
--   1. cria as tabelas novas (lojas, auditorias, auditoria_documentos);
--   2. completa colunas que faltarem nas tabelas atuais;
--   3. cria funções de permissão usadas por todas as regras;
--   4. liga o RLS e recria as políticas de todas as tabelas;
--   5. cria as funções (RPC) de log, mudança de status, resposta e perfil;
--   6. configura os buckets de Storage e suas políticas;
--   7. adiciona as tabelas ao Realtime.
--
-- ANTES DE RODAR: faça um backup (Database → Backups) ou rode primeiro num
-- projeto de teste. As políticas antigas destas tabelas são APAGADAS e
-- substituídas pelas daqui.
-- =====================================================================

