-- Grava um log. Usuário, nome, cargo e IP vêm do servidor, não do app.
create or replace function public.registrar_log(p_acao text)
returns void language plpgsql security definer set search_path = public as $$
declare
  v_user usuarios;
  v_ip   text;
begin
  select * into v_user from usuarios where id = auth.uid();
  if v_user.id is null then
    raise exception 'Usuário sem perfil.' using errcode = '42501';
  end if;

  begin
    v_ip := split_part(
      coalesce(current_setting('request.headers', true)::json ->> 'x-forwarded-for', ''),
      ',', 1);
  exception when others then
    v_ip := null;
  end;

  insert into logs (usuario_id, usuario_nome, ip, acao)
  values (v_user.id, v_user.nome || ' (' || v_user.tag || ')',
          nullif(trim(v_ip), ''), left(coalesce(p_acao, ''), 500));
end $$;

create or replace function public.mudar_status_solicitacao(p_id text, p_status text)
returns public.solicitacoes language plpgsql security definer set search_path = public as $$
declare
  v_sol solicitacoes;
begin
  if p_status not in ('pendente','em_andamento','aguardando','concluido') then
    raise exception 'Status inválido.' using errcode = '22023';
  end if;

  select * into v_sol from solicitacoes where id = p_id for update;
  if v_sol.id is null then
    raise exception 'Solicitação não encontrada.' using errcode = 'P0002';
  end if;
  if not public.pode_gerenciar_setor(v_sol.setor) then
    raise exception 'Sem permissão para este setor.' using errcode = '42501';
  end if;

  update solicitacoes
     set status = p_status, atualizado_em = now(), atualizado_por = auth.uid()
   where id = p_id
  returning * into v_sol;

  perform public.registrar_log('Alterou status da solicitação ' || p_id || ' para ' ||
    case p_status when 'pendente' then 'Pendente' when 'em_andamento' then 'Em andamento'
                  when 'aguardando' then 'Aguardando' else 'Concluído' end);
  return v_sol;
end $$;

create or replace function public.responder_solicitacao(p_id text, p_texto text)
returns public.solicitacoes language plpgsql security definer set search_path = public as $$
declare
  v_sol solicitacoes;
begin
  if coalesce(trim(p_texto), '') = '' then
    raise exception 'Resposta vazia.' using errcode = '22023';
  end if;

  select * into v_sol from solicitacoes where id = p_id for update;
  if v_sol.id is null then
    raise exception 'Solicitação não encontrada.' using errcode = 'P0002';
  end if;
  if not public.pode_gerenciar_setor(v_sol.setor) then
    raise exception 'Sem permissão para este setor.' using errcode = '42501';
  end if;

  update solicitacoes
     set resposta = left(trim(p_texto), 2000),
         respondido_por = auth.uid(),
         atualizado_em = now(),
         atualizado_por = auth.uid()
   where id = p_id
  returning * into v_sol;

  perform public.registrar_log('Respondeu a solicitação ' || p_id);
  return v_sol;
end $$;

-- "Meu Perfil": a pessoa só pode trocar o próprio nome de exibição.
create or replace function public.atualizar_meu_nome(p_nome text)
returns void language plpgsql security definer set search_path = public as $$
begin
  if coalesce(trim(p_nome), '') = '' then
    raise exception 'Nome vazio.' using errcode = '22023';
  end if;
  update usuarios set nome = left(trim(p_nome), 120)
   where id = auth.uid() and coalesce(ativo, true);
end $$;

revoke execute on function
  public.registrar_log(text),
  public.mudar_status_solicitacao(text, text),
  public.responder_solicitacao(text, text),
  public.atualizar_meu_nome(text)
  from public, anon;
grant execute on function
  public.registrar_log(text),
  public.mudar_status_solicitacao(text, text),
  public.responder_solicitacao(text, text),
  public.atualizar_meu_nome(text)
  to authenticated;

