-- usuarios: cada um lê o próprio perfil; só a Diretoria lê todos e edita.
-- Ninguém altera o próprio cargo. Novos usuários são criados pela Edge
-- Function admin-create-user (que usa a service_role e ignora o RLS).
create policy usuarios_select on public.usuarios
  for select to authenticated
  using (id = auth.uid() or public.eh_diretoria());

create policy usuarios_update_diretoria on public.usuarios
  for update to authenticated
  using (public.eh_diretoria())
  with check (public.eh_diretoria());

