-- ---------------------------------------------------------------------
-- 2. ID sequencial "SOL-0001" gerado pelo banco
-- ---------------------------------------------------------------------
-- Se você já tem um gatilho próprio que gera o ID, os dois convivem:
-- este só age quando o ID chega vazio.

create sequence if not exists public.solicitacoes_numero_seq;

select setval(
  'public.solicitacoes_numero_seq',
  greatest(
    (select coalesce(max(nullif(regexp_replace(id, '\D', '', 'g'), '')::bigint), 0)
       from public.solicitacoes),
    1
  ),
  (select count(*) > 0 from public.solicitacoes)
);

create or replace function public.solicitacoes_definir_id()
returns trigger language plpgsql security definer set search_path = public as $$
begin
  if new.id is null or new.id = '' then
    new.id := 'SOL-' || lpad(nextval('public.solicitacoes_numero_seq')::text, 4, '0');
  end if;
  -- Funciona com criado_em do tipo data ou texto (bancos antigos usam texto)
  -- Formato ISO (2026-11-25T14:07:35.765Z): o app lê igual em qualquer celular
  if new.criado_em is null then
    new.criado_em := to_char(now() at time zone 'utc', 'YYYY-MM-DD"T"HH24:MI:SS.MS"Z"');
  end if;
  if new."timestamp" is null then
    new."timestamp" := (extract(epoch from now()) * 1000)::bigint;
  end if;
  return new;
end $$;

drop trigger if exists trg_solicitacoes_definir_id on public.solicitacoes;
create trigger trg_solicitacoes_definir_id
  before insert on public.solicitacoes
  for each row execute function public.solicitacoes_definir_id();

-- ---------------------------------------------------------------------
-- 3. Funções de permissão (espelham src/lib/permissions.ts)
-- ---------------------------------------------------------------------
-- SECURITY DEFINER para poderem ler `usuarios` sem esbarrar no RLS.
-- Todas exigem conta ATIVA: desativar um usuário corta o acesso dele a
-- tudo imediatamente, mesmo que a sessão ainda esteja aberta.

create or replace function public.eh_diretoria()
returns boolean language sql stable security definer set search_path = public as $$
  select exists (
    select 1 from usuarios
    where id = auth.uid() and coalesce(ativo, true) and tag = 'Diretoria'
  );
$$;

create or replace function public.eh_usuario_ativo()
returns boolean language sql stable security definer set search_path = public as $$
  select exists (select 1 from usuarios where id = auth.uid() and coalesce(ativo, true));
$$;

-- Pode abrir e acompanhar solicitações desta loja?
create or replace function public.pode_ver_loja(p_loja text)
returns boolean language sql stable security definer set search_path = public as $$
  select exists (
    select 1 from usuarios u
    where u.id = auth.uid() and coalesce(u.ativo, true) and (
         u.tag = 'Diretoria'
      or (u.tag = 'Supervisão' and u.tipo_supervisao = 'operacao')
      or (u.tag = 'Líder' and p_loja = any(coalesce(u.lojas_acesso, '{}')))
    )
  );
$$;

-- Pode atender (mudar status / responder) solicitações deste setor?
create or replace function public.pode_gerenciar_setor(p_setor text)
returns boolean language sql stable security definer set search_path = public as $$
  select exists (
    select 1 from usuarios u
    where u.id = auth.uid() and coalesce(u.ativo, true) and (
         u.tag = 'Diretoria'
      or (u.tag = 'Supervisão' and u.tipo_supervisao = 'administrativa')
      or (u.tag = 'Central' and p_setor = any(coalesce(u.setores_acesso, '{}')))
    )
  );
$$;

-- Pode ver notas e relatórios de auditoria desta loja?
create or replace function public.pode_ver_auditoria(p_loja text)
returns boolean language sql stable security definer set search_path = public as $$
  select public.pode_ver_loja(p_loja) or exists (
    select 1 from usuarios where id = auth.uid() and coalesce(ativo, true) and tag = 'Supervisão'
  );
$$;

